def strings(lang: str) -> dict:
    return EN | STRINGS.get(lang, {})


def pick_lang(query: str | None, cookie: str | None, accept: str | None) -> str:
    """?lang= wins, then the cookie, then the browser's first known language."""
    for candidate in (query, cookie):
        if candidate in STRINGS:
            return candidate
    for part in (accept or "").split(","):
        code = part.split(";")[0].strip().lower()[:2]
        if code in STRINGS:
            return code
    return "en"
